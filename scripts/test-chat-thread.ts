/**
 * Порядок реплік у стрічці чату — за серверним часом.
 *
 * Репліки відвідувача пише сайт (`visitor[]`), відповіді власника —
 * місток із Telegram (`messages[]`). Обидва мають `at`, тож стрічка
 * впорядковується за ним. Раніше порядок тримався на полі `after`
 * (localStorage), і історія губилася між пристроями.
 *
 * Запуск: npx tsx scripts/test-chat-thread.ts
 */
import { buildRows, type Msg } from "../src/lib/chat-thread";

let ok = true;
function check(good: boolean, label: string) {
  console.log(`  ${good ? "✓" : "✗"} ${label}`);
  if (!good) ok = false;
}

function flow(visitor: Msg[], owner: Msg[]): string[] {
  return buildRows(visitor, owner).map((r) => `${r.from === "visitor" ? "Я" : "Він"}: ${r.text}`);
}

// ── 1. Порожньо ──────────────────────────────────────────────────────
check(flow([], []).length === 0, "порожня розмова — порожня стрічка");

// ── 2. Щойно надіслали, відповіді ще немає ───────────────────────────
check(
  JSON.stringify(flow([{ text: "Коли старт?", at: "2026-09-27T22:40:00" }], [])) ===
    JSON.stringify(["Я: Коли старт?"]),
  "питання без відповіді — видно лише питання",
);

// ── 3. Реальний випадок: питання → відповідь → уточнення → відповідь
const real = flow(
  [
    { text: "Коли початок групи?", at: "2026-09-27T22:40:00" },
    { text: "А о котрій?", at: "2026-09-27T22:44:00" },
  ],
  [
    { text: "Добрий день, початок групи через тиждень", at: "2026-09-27T22:43:47" },
    { text: "Так, саме 2 жовтня", at: "2026-09-27T22:45:32" },
  ],
);
check(
  JSON.stringify(real) ===
    JSON.stringify([
      "Я: Коли початок групи?",
      "Він: Добрий день, початок групи через тиждень",
      "Я: А о котрій?",
      "Він: Так, саме 2 жовтня",
    ]),
  "питання → відповідь → уточнення → друга відповідь: порядок точний",
);

// ── 4. Обидві відповіді власника поспіль ─────────────────────────────
check(
  JSON.stringify(
    flow([{ text: "Питання", at: "2026-09-27T22:40:00" }], [
      { text: "Перша", at: "2026-09-27T22:41:00" },
      { text: "Друга", at: "2026-09-27T22:42:00" },
    ]),
  ) === JSON.stringify(["Я: Питання", "Він: Перша", "Він: Друга"]),
  "дві відповіді власника поспіль видно обидві",
);

// ── 5. Лише відповідь (інший пристрій ще нічого не писав) ───────────
check(
  JSON.stringify(flow([], [{ text: "Відповідь", at: "2026-09-27T22:43:00" }])) ===
    JSON.stringify(["Він: Відповідь"]),
  "лише відповідь власника",
);

// ── 6. Три цикли — чергування не збивається ──────────────────────────
check(
  JSON.stringify(
    flow(
      [
        { text: "п1", at: "2026-09-27T22:40:00" },
        { text: "п2", at: "2026-09-27T22:42:00" },
        { text: "п3", at: "2026-09-27T22:44:00" },
      ],
      [
        { text: "в1", at: "2026-09-27T22:41:00" },
        { text: "в2", at: "2026-09-27T22:43:00" },
        { text: "в3", at: "2026-09-27T22:45:00" },
      ],
    ),
  ) === JSON.stringify(["Я: п1", "Він: в1", "Я: п2", "Він: в2", "Я: п3", "Він: в3"]),
  "три цикли уточнень — ідеальне чергування",
);

// ── 7. Два питання підряд, потім дві відповіді — пачка не перемішується
check(
  JSON.stringify(
    flow(
      [
        { text: "п1", at: "2026-09-27T22:40:00" },
        { text: "п2", at: "2026-09-27T22:40:01" },
      ],
      [
        { text: "в1", at: "2026-09-27T22:41:00" },
        { text: "в2", at: "2026-09-27T22:41:10" },
      ],
    ),
  ) === JSON.stringify(["Я: п1", "Я: п2", "Він: в1", "Він: в2"]),
  "два питання підряд, потім дві відповіді — без перемішування",
);

// ── 8. Нормування часу: «T» і пробіл не розводять однаковий час в різні боки
check(
  JSON.stringify(
    flow(
      [{ text: "п1", at: "2026-09-27 22:40:00" }],
      [{ text: "в1", at: "2026-09-27T22:40:00" }],
    ),
  ) === JSON.stringify(["Я: п1", "Він: в1"]),
  "«T» і пробіл у мітці часу не ламають порядок",
);

console.log("\nРЕЗУЛЬТАТ:", ok ? "✓ ПРОЙДЕНО" : "✗ Є ПОМИЛКИ");
process.exit(ok ? 0 : 1);
