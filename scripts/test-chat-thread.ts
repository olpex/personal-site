/**
 * Тест порядку реплік у стрічці чату.
 *
 * Перевіряємо саме те, що ламалося в житті: питання → відповідь →
 * уточнення → друга відповідь має стояти в правильному порядку,
 * навіть після перезавантаження сторінки.
 *
 * Запуск: npx tsx scripts/test-chat-thread.ts
 */
import { buildRows, type LocalMsg, type OwnerMsg } from "../src/lib/chat-thread";

let ok = true;
function check(good: boolean, label: string) {
  console.log(`  ${good ? "✓" : "✗"} ${label}`);
  if (!good) ok = false;
}

function flow(local: LocalMsg[], owner: OwnerMsg[]): string[] {
  return buildRows(local, owner).map((r) => `${r.from === "visitor" ? "Я" : "Він"}: ${r.text}`);
}

// ── 1. Порожньо ──────────────────────────────────────────────────────
check(flow([], []).length === 0, "порожня розмова — порожня стрічка");

// ── 2. Щойно надіслали, відповіді ще немає ───────────────────────────
check(
  JSON.stringify(flow([{ text: "Коли старт?", at: "", after: 0 }], [])) ===
    JSON.stringify(["Я: Коли старт?"]),
  "питання без відповіді — видно лише питання",
);

// ── 3. Реальний випадок із життя: питання → відповідь → уточнення → відповідь
const real = flow(
  [
    { text: "Коли початок групи?", at: "", after: 0 },
    { text: "А о котрій?", at: "", after: 1 },
  ],
  [
    { text: "Добрий день, початок групи через тиждень", at: "" },
    { text: "Так, саме 2 жовтня", at: "" },
  ],
);
check(
  JSON.stringify(real) ===
    JSON.stringify([
      "Я: Коли початок групи?",
      "Він: Добрий день, початок групи через тиждень",
      "Я: А о котрій?",
      "Він: Так, саме 2 жовтня",
    ]),
  "питання → відповідь → уточнення → друга відповідь: порядок точний",
);

// ── 4. Обидві відповіді власника на одне питання (без уточнення) ─────
const two = flow(
  [{ text: "Питання", at: "", after: 0 }],
  [{ text: "Перша", at: "" }, { text: "Друга", at: "" }],
);
check(
  JSON.stringify(two) === JSON.stringify(["Я: Питання", "Він: Перша", "Він: Друга"]),
  "дві відповіді власника поспіль видно обидві",
);

// ── 5. Відповідь прийшла, але локальних реплік немає (інший браузер) ──
const onlyOwner = flow([], [{ text: "Відповідь", at: "" }]);
check(JSON.stringify(onlyOwner) === JSON.stringify(["Він: Відповідь"]), "лише відповідь власника");

// ── 6. Три цикли — чергування не збивається ──────────────────────────
const many = flow(
  [
    { text: "п1", at: "", after: 0 },
    { text: "п2", at: "", after: 1 },
    { text: "п3", at: "", after: 2 },
  ],
  [{ text: "в1", at: "" }, { text: "в2", at: "" }, { text: "в3", at: "" }],
);
check(
  JSON.stringify(many) ===
    JSON.stringify(["Я: п1", "Він: в1", "Я: п2", "Він: в2", "Я: п3", "Він: в3"]),
  "три цикли уточнень — ідеальне чергування",
);

// ── 7. Уточнення надіслали ДО того, як прийшла відповідь ─────────────
// (людина написала двічі підряд, потім власник відповів двічі)
const burst = flow(
  [
    { text: "п1", at: "", after: 0 },
    { text: "п2", at: "", after: 0 },
  ],
  [{ text: "в1", at: "" }, { text: "в2", at: "" }],
);
check(
  JSON.stringify(burst) === JSON.stringify(["Я: п1", "Я: п2", "Він: в1", "Він: в2"]),
  "два питання підряд, потім дві відповіді — без перемішування",
);

console.log("\nРЕЗУЛЬТАТ:", ok ? "✓ ПРОЙДЕНО" : "✗ Є ПОМИЛКИ");
process.exit(ok ? 0 : 1);
